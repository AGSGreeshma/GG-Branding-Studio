import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

/*
 * One committed results file, several runners (plan §21.1, ADR-025).
 * Each runner owns a marked section and rewrites only that, so running
 * `pnpm eval:battle` never wipes the Anti-Generic results and vice versa.
 */

const HEADER = `# Evaluation results

_Generated by the eval harness in \`evals/\` (plan §21.1). Each section is rewritten by its own runner; raw per-run JSON stays out of git._
`;

function markers(key: string): { start: string; end: string } {
  return { start: `<!-- eval:${key} -->`, end: `<!-- /eval:${key} -->` };
}

/** Replaces (or appends) one runner's section in the shared summary file. */
export function writeSection(path: string, key: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  const { start, end } = markers(key);
  const block = `${start}\n${content.trim()}\n${end}`;

  const existing = existsSync(path) ? readFileSync(path, "utf8") : `${HEADER}\n`;
  const from = existing.indexOf(start);
  const to = existing.indexOf(end);

  const next =
    from !== -1 && to !== -1
      ? `${existing.slice(0, from)}${block}${existing.slice(to + end.length)}`
      : `${existing.trimEnd()}\n\n${block}\n`;

  writeFileSync(path, next.endsWith("\n") ? next : `${next}\n`);
}
